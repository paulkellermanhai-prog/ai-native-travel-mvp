-- Isolated candidate only: do not add to the shared migration chain or grant
-- EXECUTE until this slice has real PostgreSQL and least-privilege review.
-- It has no reader or association capability.
CREATE TABLE public."HostEvidenceWorkspace" (
  owner_id TEXT NOT NULL CHECK (char_length(owner_id) BETWEEN 1 AND 256),
  trip_id TEXT NOT NULL CHECK (trip_id ~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$'),
  workspace_key TEXT NOT NULL CHECK (workspace_key ~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$'),
  session_ref TEXT NOT NULL CHECK (char_length(session_ref) BETWEEN 1 AND 256),
  retention_revision BIGINT NOT NULL DEFAULT 0 CHECK (retention_revision BETWEEN 0 AND 9007199254740991),
  PRIMARY KEY (owner_id,trip_id,workspace_key)
);
REVOKE ALL ON public."HostEvidenceWorkspace" FROM PUBLIC;
-- Written only by a future trusted lifecycle adapter; no writer is granted in
-- this candidate. Missing/stale lifecycle evidence must close event reads.
CREATE TABLE public."HostEvidenceTripLifecycle" (
  trip_id TEXT PRIMARY KEY,
  source_revision BIGINT NOT NULL CHECK (source_revision BETWEEN 0 AND 9007199254740991),
  ended_at TIMESTAMPTZ(6)
);
REVOKE ALL ON public."HostEvidenceTripLifecycle" FROM PUBLIC;
CREATE TABLE public."HostEvidenceEvent" (
  sequence BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY CHECK (sequence <= 9007199254740991),
  owner_id TEXT NOT NULL CHECK (char_length(owner_id) BETWEEN 1 AND 256),
  trip_id TEXT NOT NULL CHECK (trip_id ~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$'),
  workspace_key TEXT NOT NULL CHECK (workspace_key ~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$'),
  event_id TEXT NOT NULL UNIQUE CHECK (event_id ~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$'),
  session_ref TEXT CHECK (session_ref IS NULL OR char_length(session_ref) BETWEEN 1 AND 256),
  entry TEXT NOT NULL CHECK (entry IN ('dialogue','map','timeline','comparison')),
  body TEXT CHECK (body IS NULL OR char_length(body) BETWEEN 1 AND 16000),
  received_at TIMESTAMPTZ(6) NOT NULL,
  recorded_at TIMESTAMPTZ(6) NOT NULL DEFAULT clock_timestamp(),
  key_token TEXT NOT NULL CHECK (key_token ~ '^[0-9a-f]{64}$'),
  input_digest TEXT CHECK (input_digest IS NULL OR input_digest ~ '^[0-9a-f]{64}$'),
  policy TEXT NOT NULL CHECK (policy = 'DC-AC8-PRIVACY-01'),
  deleted_at TIMESTAMPTZ(6),
  UNIQUE (owner_id, trip_id, workspace_key, key_token),
  FOREIGN KEY (owner_id,trip_id,workspace_key) REFERENCES public."HostEvidenceWorkspace" (owner_id,trip_id,workspace_key),
  CHECK (deleted_at IS NOT NULL OR (body IS NOT NULL AND input_digest IS NOT NULL AND session_ref IS NOT NULL))
);
REVOKE ALL ON public."HostEvidenceEvent" FROM PUBLIC;
REVOKE ALL ON SEQUENCE public."HostEvidenceEvent_sequence_seq" FROM PUBLIC;

CREATE TABLE public."HostEvidenceCleanup" (
  event_id TEXT PRIMARY KEY REFERENCES public."HostEvidenceEvent" (event_id),
  deletion_revision BIGINT NOT NULL,
  requested_at TIMESTAMPTZ(6) NOT NULL,
  completed_at TIMESTAMPTZ(6)
);
REVOKE ALL ON public."HostEvidenceCleanup" FROM PUBLIC;

-- A workspace key is generated by the authenticated server; the returned key
-- is only usable through a server-held capability bound to the same session.
CREATE FUNCTION public.host_evidence_workspace_candidate(p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
BEGIN
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN RETURN FALSE; END IF;
  INSERT INTO public."HostEvidenceWorkspace" (owner_id,trip_id,workspace_key,session_ref) VALUES (p_owner,p_trip,p_workspace,p_session);
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_workspace_candidate(TEXT,TEXT,TEXT,TEXT) FROM PUBLIC;

-- Authenticated host supplies the session and server-bound workspace; an input
-- string alone never proves workspace ownership. Denied paths return no row data.
CREATE FUNCTION public.host_evidence_record_candidate(
  p_session TEXT, p_owner TEXT, p_trip TEXT, p_workspace TEXT, p_event TEXT,
  p_entry TEXT, p_body TEXT, p_received TIMESTAMPTZ, p_key TEXT, p_digest TEXT
) RETURNS TABLE(disposition TEXT, out_event_id TEXT, out_sequence BIGINT, out_recorded_at TIMESTAMPTZ)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE e public."HostEvidenceEvent"%ROWTYPE;
BEGIN
  IF public.authorize_trip_session(p_session, p_owner, p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT 'denied'::TEXT, NULL::TEXT, NULL::BIGINT, NULL::TIMESTAMPTZ;
    RETURN;
  END IF;
  PERFORM 1 FROM public."HostEvidenceWorkspace" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND session_ref=p_session FOR SHARE;
  IF NOT FOUND THEN
    RETURN QUERY SELECT 'denied'::TEXT, NULL::TEXT, NULL::BIGINT, NULL::TIMESTAMPTZ;
    RETURN;
  END IF;
  INSERT INTO public."HostEvidenceEvent" (owner_id,trip_id,workspace_key,event_id,session_ref,entry,body,received_at,key_token,input_digest,policy)
    VALUES (p_owner,p_trip,p_workspace,p_event,p_session,p_entry,p_body,p_received,p_key,p_digest,'DC-AC8-PRIVACY-01')
    ON CONFLICT (owner_id,trip_id,workspace_key,key_token) DO NOTHING
    RETURNING * INTO e;
  IF FOUND THEN
    RETURN QUERY SELECT 'inserted'::TEXT, e.event_id, e.sequence, e.recorded_at;
    RETURN;
  END IF;
  SELECT * INTO e FROM public."HostEvidenceEvent" WHERE owner_id=p_owner AND trip_id=p_trip
    AND workspace_key=p_workspace AND key_token=p_key FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'event receipt unavailable'; END IF;
  IF e.deleted_at IS NOT NULL THEN
    RETURN QUERY SELECT 'deleted'::TEXT, NULL::TEXT, NULL::BIGINT, NULL::TIMESTAMPTZ;
  ELSIF e.input_digest <> p_digest OR e.entry <> p_entry OR e.body <> p_body THEN
    RETURN QUERY SELECT 'conflict'::TEXT, NULL::TEXT, NULL::BIGINT, NULL::TIMESTAMPTZ;
  ELSE
    RETURN QUERY SELECT 'replayed'::TEXT, e.event_id, e.sequence, e.recorded_at;
  END IF;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_record_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TIMESTAMPTZ,TEXT,TEXT) FROM PUBLIC;

-- Internal, proof-bound read. There is no association implementation yet;
-- this function does not prove that an event is unlinked or single-use.
-- No lifecycle writer exists yet; absent/stale evidence fails closed.
CREATE FUNCTION public.host_evidence_for_turn_candidate(p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_event TEXT,p_token TEXT,p_metadata_only BOOLEAN)
RETURNS TABLE(allowed BOOLEAN, out_entry TEXT, out_body TEXT, out_received_at TIMESTAMPTZ)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public SET timezone='UTC' AS $$
DECLARE e public."HostEvidenceEvent"%ROWTYPE; l public."HostEvidenceTripLifecycle"%ROWTYPE; v_revision BIGINT;
BEGIN
  SELECT "revision" INTO v_revision FROM public."TripStateDocument" WHERE "tripId"=p_trip FOR SHARE;
  IF NOT FOUND THEN RETURN QUERY SELECT FALSE,NULL::TEXT,NULL::TEXT,NULL::TIMESTAMPTZ; RETURN; END IF;
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT FALSE,NULL::TEXT,NULL::TEXT,NULL::TIMESTAMPTZ; RETURN;
  END IF;
  PERFORM 1 FROM public."HostEvidenceWorkspace" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND session_ref=p_session FOR SHARE;
  IF NOT FOUND THEN RETURN QUERY SELECT FALSE,NULL::TEXT,NULL::TEXT,NULL::TIMESTAMPTZ; RETURN; END IF;
  SELECT * INTO l FROM public."HostEvidenceTripLifecycle" WHERE trip_id=p_trip AND source_revision=v_revision FOR SHARE;
  IF NOT FOUND OR (l.ended_at IS NOT NULL AND (l.ended_at > clock_timestamp() OR clock_timestamp() >= l.ended_at + interval '30 days')) THEN
    RETURN QUERY SELECT FALSE,NULL::TEXT,NULL::TEXT,NULL::TIMESTAMPTZ; RETURN;
  END IF;
  SELECT * INTO e FROM public."HostEvidenceEvent" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND event_id=p_event FOR SHARE;
  IF NOT FOUND OR e.key_token IS DISTINCT FROM p_token OR e.deleted_at IS NOT NULL OR e.body IS NULL OR e.recorded_at > clock_timestamp() OR clock_timestamp() >= e.recorded_at + interval '180 days' OR clock_timestamp() >= e.recorded_at + interval '12 months' THEN
    RETURN QUERY SELECT FALSE,NULL::TEXT,NULL::TEXT,NULL::TIMESTAMPTZ; RETURN;
  END IF;
  RETURN QUERY SELECT TRUE,CASE WHEN p_metadata_only THEN NULL ELSE e.entry END,CASE WHEN p_metadata_only THEN NULL ELSE e.body END,CASE WHEN p_metadata_only THEN NULL ELSE e.received_at END;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_for_turn_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,BOOLEAN) FROM PUBLIC;

-- Serializes deletion with writes in the same workspace. A committed marker
-- always precedes physical cleanup; repeat requests do not advance revision.
CREATE FUNCTION public.host_evidence_delete_candidate(p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_event TEXT)
RETURNS TABLE(disposition TEXT, deletion_revision BIGINT, accepted_at TIMESTAMPTZ, cleanup_pending BOOLEAN)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE e public."HostEvidenceEvent"%ROWTYPE; c public."HostEvidenceCleanup"%ROWTYPE; v_revision BIGINT;
BEGIN
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN;
  END IF;
  PERFORM 1 FROM public."HostEvidenceWorkspace" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND session_ref=p_session FOR UPDATE;
  IF NOT FOUND THEN RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN; END IF;
  SELECT * INTO e FROM public."HostEvidenceEvent" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND event_id=p_event FOR UPDATE;
  IF NOT FOUND THEN RETURN QUERY SELECT 'missing'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN; END IF;
  IF e.deleted_at IS NULL THEN
    UPDATE public."HostEvidenceWorkspace" SET retention_revision=retention_revision+1
      WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace RETURNING retention_revision INTO v_revision;
    UPDATE public."HostEvidenceEvent" SET deleted_at=clock_timestamp() WHERE event_id=p_event RETURNING * INTO e;
    INSERT INTO public."HostEvidenceCleanup" (event_id,deletion_revision,requested_at) VALUES (p_event,v_revision,e.deleted_at);
  END IF;
  SELECT * INTO STRICT c FROM public."HostEvidenceCleanup" WHERE event_id=p_event;
  RETURN QUERY SELECT 'deleted'::TEXT,c.deletion_revision,c.requested_at,c.completed_at IS NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_delete_candidate(TEXT,TEXT,TEXT,TEXT,TEXT) FROM PUBLIC;

-- Separate maintenance capability; no grant is issued here. A failed cleanup
-- leaves the committed deletion marker and pending job intact.
CREATE FUNCTION public.host_evidence_cleanup_candidate(p_event TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE c public."HostEvidenceCleanup"%ROWTYPE;
BEGIN
  SELECT * INTO c FROM public."HostEvidenceCleanup" WHERE event_id=p_event FOR UPDATE;
  IF NOT FOUND THEN RETURN FALSE; END IF;
  IF c.completed_at IS NOT NULL THEN RETURN TRUE; END IF;
  UPDATE public."HostEvidenceEvent" SET body=NULL,input_digest=NULL,session_ref=NULL WHERE event_id=p_event AND deleted_at IS NOT NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'deletion marker missing'; END IF;
  UPDATE public."HostEvidenceCleanup" SET completed_at=clock_timestamp() WHERE event_id=p_event;
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_cleanup_candidate(TEXT) FROM PUBLIC;

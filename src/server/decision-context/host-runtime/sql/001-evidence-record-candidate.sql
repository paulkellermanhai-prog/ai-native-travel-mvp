-- Only the trusted host calls this after validating the Task against the
-- source and current state. The source is re-authorized and held to commit.
CREATE FUNCTION public.host_evidence_bind_task_source_candidate(
  p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_capability TEXT,
  p_task_token TEXT,p_task JSONB,p_event TEXT,p_event_token TEXT,p_turn_id TEXT
) RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE ok BOOLEAN; v_revision BIGINT; v_action TEXT; v_task_key TEXT; v_bound_key TEXT; v_task_digest TEXT;
BEGIN
  v_task_key:=p_task->>'task_key';
  IF p_task_token IS NULL OR p_task_token !~ '^[0-9a-f]{64}$' OR jsonb_typeof(p_task) IS DISTINCT FROM 'object' OR
    v_task_key IS NULL OR v_task_key !~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$' OR
    p_turn_id IS NULL OR p_turn_id !~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$' THEN RETURN FALSE; END IF;
  SELECT allowed INTO ok FROM public.host_evidence_for_turn_candidate(p_session,p_owner,p_trip,p_workspace,p_capability,p_event,p_event_token,TRUE);
  IF ok IS DISTINCT FROM TRUE THEN RETURN FALSE; END IF;
  v_task_digest:=encode(sha256(convert_to(p_capability||v_task_key,'UTF8')),'hex');
  INSERT INTO public."HostEvidenceAssociationHead"(owner_id,trip_id,workspace_key,task_token,task_key_digest)
    VALUES(p_owner,p_trip,p_workspace,p_task_token,v_task_digest) ON CONFLICT DO NOTHING;
  SELECT revision,task_key_digest INTO v_revision,v_bound_key FROM public."HostEvidenceAssociationHead"
    WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND task_token=p_task_token FOR UPDATE;
  IF v_bound_key IS DISTINCT FROM v_task_digest THEN RETURN FALSE; END IF;
  SELECT action INTO v_action FROM public."HostEvidenceAssociationLog"
    WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND task_token=p_task_token AND event_id=p_event
    ORDER BY association_revision DESC LIMIT 1;
  -- A normal registration cannot revive an explicitly retracted source.
  IF v_action IN ('unlink','supersede') THEN RETURN FALSE; END IF;
  IF v_action IS DISTINCT FROM 'link' THEN
    UPDATE public."HostEvidenceAssociationHead" SET revision=revision+1
      WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND task_token=p_task_token;
    INSERT INTO public."HostEvidenceAssociationLog"(link_id,owner_id,trip_id,workspace_key,task_token,task_key_digest,event_id,
      action,association_revision,expected_association_revision,source_turn_id,operation_token)
      VALUES('link_'||replace(gen_random_uuid()::text,'-',''),p_owner,p_trip,p_workspace,p_task_token,v_task_digest,p_event,
        'link',v_revision+1,v_revision,p_turn_id,
        encode(sha256(convert_to(p_capability||p_turn_id||p_task_token||p_event||'link','UTF8')),'hex'));
  END IF;
  INSERT INTO public."HostEvidenceTaskSource"(owner_id,trip_id,workspace_key,task_token,task_digest,event_id,event_token)
    VALUES(p_owner,p_trip,p_workspace,p_task_token,encode(sha256(convert_to(p_capability || p_task::text,'UTF8')),'hex'),p_event,p_event_token)
    ON CONFLICT DO NOTHING;
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'source authorization expired' USING ERRCODE='42501';
  END IF;
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_bind_task_source_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,JSONB,TEXT,TEXT,TEXT) FROM PUBLIC;

-- Bounded, metadata-only snapshot of one minted Task's committed source set.
-- The host verifies every event through host_evidence_for_turn_candidate before
-- exposing text. Workspace FOR UPDATE linearizes association/deletion changes
-- with the cursor snapshot; no caller-provided task string is authority alone.
CREATE FUNCTION public.host_evidence_task_snapshot_candidate(
  p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_capability TEXT,p_task_key TEXT,p_task_token TEXT
) RETURNS TABLE(ok BOOLEAN,out_retention_revision BIGINT,out_highwater BIGINT,out_association_revision BIGINT,out_unlinked_count BIGINT,out_sources JSONB)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE v_retention BIGINT; v_highwater BIGINT; v_count BIGINT; v_association BIGINT; v_unlinked BIGINT; v_sources JSONB;
BEGIN
  IF p_task_token !~ '^[0-9a-f]{64}$' OR public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT FALSE,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::JSONB; RETURN;
  END IF;
  SELECT retention_revision INTO v_retention FROM public."HostEvidenceWorkspace"
    WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace
      AND session_ref=p_session AND capability_token=p_capability FOR UPDATE;
  IF NOT FOUND OR public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE OR NOT EXISTS (
    SELECT 1 FROM public."HostEvidenceTaskKey" WHERE owner_id=p_owner AND trip_id=p_trip
      AND workspace_key=p_workspace AND task_key=p_task_key) THEN
    RETURN QUERY SELECT FALSE,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::JSONB; RETURN;
  END IF;
  SELECT count(*) INTO v_count FROM public."HostEvidenceTaskSource" WHERE owner_id=p_owner AND trip_id=p_trip
    AND workspace_key=p_workspace AND task_token=p_task_token;
  SELECT revision INTO v_association FROM public."HostEvidenceAssociationHead" WHERE owner_id=p_owner AND trip_id=p_trip
    AND workspace_key=p_workspace AND task_token=p_task_token FOR SHARE;
  IF v_count<1 OR v_count>256 OR EXISTS (
    SELECT 1 FROM public."HostEvidenceTaskSource" b LEFT JOIN public."HostEvidenceEvent" e ON e.event_id=b.event_id
    WHERE b.owner_id=p_owner AND b.trip_id=p_trip AND b.workspace_key=p_workspace AND b.task_token=p_task_token
      AND (e.event_id IS NULL OR e.owner_id IS DISTINCT FROM p_owner OR e.trip_id IS DISTINCT FROM p_trip
        OR e.workspace_key IS DISTINCT FROM p_workspace OR e.key_token IS DISTINCT FROM b.event_token OR
        (SELECT action FROM public."HostEvidenceAssociationLog" l WHERE l.owner_id=b.owner_id AND l.trip_id=b.trip_id
          AND l.workspace_key=b.workspace_key AND l.task_token=b.task_token AND l.event_id=b.event_id
          ORDER BY l.association_revision DESC LIMIT 1) IS DISTINCT FROM 'link')) OR v_association IS NULL THEN
    RETURN QUERY SELECT FALSE,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::JSONB; RETURN;
  END IF;
  SELECT COALESCE(MAX(sequence),0) INTO v_highwater FROM public."HostEvidenceEvent"
    WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace;
  SELECT count(*) INTO v_unlinked FROM public."HostEvidenceEvent" e
    WHERE e.owner_id=p_owner AND e.trip_id=p_trip AND e.workspace_key=p_workspace AND e.deleted_at IS NULL
      AND NOT EXISTS (SELECT 1 FROM public."HostEvidenceTaskSource" b WHERE b.owner_id=p_owner AND b.trip_id=p_trip
        AND b.workspace_key=p_workspace AND b.event_id=e.event_id);
  SELECT COALESCE(jsonb_agg(jsonb_build_object('event_id',s.event_id,'event_token',s.event_token,
    'sequence',s.sequence,'recorded_at',s.recorded_at) ORDER BY s.sequence),'[]'::jsonb) INTO v_sources FROM (
    SELECT b.event_id,MIN(b.event_token) AS event_token,e.sequence,e.recorded_at
    FROM public."HostEvidenceTaskSource" b JOIN public."HostEvidenceEvent" e ON e.event_id=b.event_id
    WHERE b.owner_id=p_owner AND b.trip_id=p_trip AND b.workspace_key=p_workspace AND b.task_token=p_task_token
    GROUP BY b.event_id,e.sequence,e.recorded_at
  ) s;
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT FALSE,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::BIGINT,NULL::JSONB; RETURN;
  END IF;
  RETURN QUERY SELECT TRUE,v_retention,v_highwater,v_association,v_unlinked,v_sources;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_task_snapshot_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TEXT) FROM PUBLIC;

-- A trusted host can retract one effective Task/source link. A correction is
-- append-only; the original event remains available for other Tasks. Advance
-- the workspace barrier and remove saved scene text in the same transaction so
-- an already assembled Turn/Packet/Checkpoint cannot outlive the correction.
CREATE FUNCTION public.host_evidence_unlink_task_source_candidate(
  p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_capability TEXT,
  p_task_key TEXT,p_task_token TEXT,p_event TEXT,p_event_token TEXT,p_turn_id TEXT,
  p_expected BIGINT,p_operation TEXT
) RETURNS TABLE(disposition TEXT,out_association_revision BIGINT,out_retention_revision BIGINT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE v_revision BIGINT; v_digest TEXT; v_action TEXT; v_last_turn TEXT; v_prior public."HostEvidenceAssociationLog"%ROWTYPE;
BEGIN
  IF p_task_key !~ '^task-[0-9a-f]{32}$' OR p_task_token !~ '^[0-9a-f]{64}$' OR
     p_turn_id !~ '^[A-Za-z][A-Za-z0-9_-]{0,95}$' OR p_operation !~ '^[0-9a-f]{64}$' OR
     p_expected < 0 OR p_expected >= 9007199254740991 OR
     public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::BIGINT; RETURN;
  END IF;
  SELECT w.retention_revision INTO v_revision FROM public."HostEvidenceWorkspace" w
    WHERE w.owner_id=p_owner AND w.trip_id=p_trip AND w.workspace_key=p_workspace
      AND w.session_ref=p_session AND w.capability_token=p_capability FOR UPDATE;
  IF NOT FOUND OR public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE OR NOT EXISTS (
    SELECT 1 FROM public."HostEvidenceTaskKey" WHERE owner_id=p_owner AND trip_id=p_trip
      AND workspace_key=p_workspace AND task_key=p_task_key) THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::BIGINT; RETURN;
  END IF;
  v_digest:=encode(sha256(convert_to(p_capability||p_task_key,'UTF8')),'hex');
  SELECT h.revision,h.task_key_digest INTO v_revision,v_digest FROM public."HostEvidenceAssociationHead" h
    WHERE h.owner_id=p_owner AND h.trip_id=p_trip AND h.workspace_key=p_workspace
      AND h.task_token=p_task_token FOR UPDATE;
  IF NOT FOUND OR v_digest IS DISTINCT FROM encode(sha256(convert_to(p_capability||p_task_key,'UTF8')),'hex') THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::BIGINT; RETURN;
  END IF;
  SELECT * INTO v_prior FROM public."HostEvidenceAssociationLog" l WHERE l.owner_id=p_owner AND l.trip_id=p_trip
    AND l.workspace_key=p_workspace AND l.task_token=p_task_token AND l.operation_token=p_operation;
  IF FOUND THEN
    IF v_prior.event_id=p_event AND v_prior.action='unlink' AND v_prior.source_turn_id=p_turn_id AND
       v_prior.expected_association_revision=p_expected AND public.authorize_trip_session(p_session,p_owner,p_trip) IS TRUE THEN
      RETURN QUERY SELECT 'replayed'::TEXT,v_prior.association_revision,w.retention_revision
        FROM public."HostEvidenceWorkspace" w WHERE w.owner_id=p_owner AND w.trip_id=p_trip AND w.workspace_key=p_workspace;
    ELSE RETURN QUERY SELECT 'conflict'::TEXT,NULL::BIGINT,NULL::BIGINT; END IF;
    RETURN;
  END IF;
  IF v_revision IS DISTINCT FROM p_expected THEN
    RETURN QUERY SELECT 'conflict'::TEXT,NULL::BIGINT,NULL::BIGINT; RETURN;
  END IF;
  SELECT l.action,l.source_turn_id INTO v_action,v_last_turn FROM public."HostEvidenceAssociationLog" l
    WHERE l.owner_id=p_owner AND l.trip_id=p_trip AND l.workspace_key=p_workspace AND l.task_token=p_task_token
      AND l.event_id=p_event ORDER BY l.association_revision DESC LIMIT 1;
  IF v_action IS DISTINCT FROM 'link' OR v_last_turn IS DISTINCT FROM p_turn_id OR NOT EXISTS (
    SELECT 1 FROM public."HostEvidenceTaskSource" b WHERE b.owner_id=p_owner AND b.trip_id=p_trip
      AND b.workspace_key=p_workspace AND b.task_token=p_task_token AND b.event_id=p_event AND b.event_token=p_event_token)
    OR NOT EXISTS (SELECT 1 FROM public.host_evidence_for_turn_candidate(p_session,p_owner,p_trip,p_workspace,
      p_capability,p_event,p_event_token,TRUE) f WHERE f.allowed) THEN
    RETURN QUERY SELECT 'conflict'::TEXT,NULL::BIGINT,NULL::BIGINT; RETURN;
  END IF;
  UPDATE public."HostEvidenceAssociationHead" h SET revision=revision+1 WHERE h.owner_id=p_owner AND h.trip_id=p_trip
    AND h.workspace_key=p_workspace AND h.task_token=p_task_token;
  INSERT INTO public."HostEvidenceAssociationLog"(link_id,owner_id,trip_id,workspace_key,task_token,task_key_digest,event_id,
    action,association_revision,expected_association_revision,source_turn_id,operation_token)
    VALUES('link_'||replace(gen_random_uuid()::text,'-',''),p_owner,p_trip,p_workspace,p_task_token,v_digest,p_event,
      'unlink',v_revision+1,v_revision,p_turn_id,p_operation);
  DELETE FROM public."HostEvidenceTaskSource" b WHERE b.owner_id=p_owner AND b.trip_id=p_trip AND b.workspace_key=p_workspace
    AND b.task_token=p_task_token AND b.event_id=p_event;
  DELETE FROM public."HostEvidenceScene" s WHERE s.owner_id=p_owner AND s.trip_id=p_trip AND s.workspace_key=p_workspace;
  UPDATE public."HostEvidenceWorkspace" w SET retention_revision=retention_revision+1
    WHERE w.owner_id=p_owner AND w.trip_id=p_trip AND w.workspace_key=p_workspace
    RETURNING w.retention_revision INTO v_revision;
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'association authorization expired' USING ERRCODE='42501';
  END IF;
  RETURN QUERY SELECT 'unlinked'::TEXT,p_expected+1,v_revision;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_unlink_task_source_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,TEXT,BIGINT,TEXT) FROM PUBLIC;

-- Serializes deletion with writes in the same workspace. A committed marker
-- always precedes physical cleanup; repeat requests do not advance revision.
CREATE FUNCTION public.host_evidence_delete_candidate(p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_capability TEXT,p_event TEXT)
RETURNS TABLE(disposition TEXT, deletion_revision BIGINT, accepted_at TIMESTAMPTZ, cleanup_pending BOOLEAN)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE e public."HostEvidenceEvent"%ROWTYPE; c public."HostEvidenceCleanup"%ROWTYPE; v_revision BIGINT;
BEGIN
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN;
  END IF;
  PERFORM 1 FROM public."HostEvidenceWorkspace" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND session_ref=p_session AND capability_token=p_capability FOR UPDATE;
  IF NOT FOUND THEN RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN; END IF;
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN;
  END IF;
  SELECT * INTO e FROM public."HostEvidenceEvent" WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace AND event_id=p_event FOR UPDATE;
  IF NOT FOUND THEN RETURN QUERY SELECT 'missing'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN; END IF;
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN
    RETURN QUERY SELECT 'denied'::TEXT,NULL::BIGINT,NULL::TIMESTAMPTZ,NULL::BOOLEAN; RETURN;
  END IF;
  IF e.deleted_at IS NULL THEN
    UPDATE public."HostEvidenceWorkspace" SET retention_revision=retention_revision+1
      WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace RETURNING retention_revision INTO v_revision;
    UPDATE public."HostEvidenceEvent" SET deleted_at=clock_timestamp() WHERE event_id=p_event RETURNING * INTO e;
    INSERT INTO public."HostEvidenceCleanup" (event_id,deletion_revision,requested_at) VALUES (p_event,v_revision,e.deleted_at);
  END IF;
  SELECT * INTO STRICT c FROM public."HostEvidenceCleanup" WHERE event_id=p_event;
  RETURN QUERY SELECT 'deleted'::TEXT,c.deletion_revision,c.requested_at,c.completed_at IS NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_delete_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,TEXT) FROM PUBLIC;

-- Candidate probe only, not permission to read/write a checkpoint. Any future
-- checkpoint operation must perform these checks AND its E11 source checks in
-- the same transaction while holding the locks; this probe returns no payload.
CREATE FUNCTION public.host_evidence_checkpoint_probe_candidate(
  p_session TEXT,p_owner TEXT,p_trip TEXT,p_workspace TEXT,p_capability TEXT,p_revision BIGINT
) RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE v_document_revision BIGINT; w_revision BIGINT; l public."HostEvidenceTripLifecycle"%ROWTYPE;
BEGIN
  SELECT "revision" INTO v_document_revision FROM public."TripStateDocument" WHERE "tripId"=p_trip FOR SHARE;
  IF NOT FOUND OR public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN RETURN FALSE; END IF;
  SELECT retention_revision INTO w_revision FROM public."HostEvidenceWorkspace"
    WHERE owner_id=p_owner AND trip_id=p_trip AND workspace_key=p_workspace
      AND session_ref=p_session AND capability_token=p_capability FOR SHARE;
  IF NOT FOUND THEN RETURN FALSE; END IF;
  SELECT * INTO l FROM public."HostEvidenceTripLifecycle" WHERE trip_id=p_trip AND source_revision=v_document_revision FOR SHARE;
  IF NOT FOUND OR (l.ended_at IS NOT NULL AND (l.ended_at > clock_timestamp() OR clock_timestamp() >= l.ended_at + interval '30 days')) THEN RETURN FALSE; END IF;
  -- Waiting on either row can outlive the original session.
  IF public.authorize_trip_session(p_session,p_owner,p_trip) IS DISTINCT FROM TRUE THEN RETURN FALSE; END IF;
  RETURN p_revision IS NOT NULL AND w_revision = p_revision;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_checkpoint_probe_candidate(TEXT,TEXT,TEXT,TEXT,TEXT,BIGINT) FROM PUBLIC;

-- Separate maintenance capability; no grant is issued here. A failed cleanup
-- leaves the committed deletion marker and pending job intact.
CREATE FUNCTION public.host_evidence_cleanup_candidate(p_event TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE c public."HostEvidenceCleanup"%ROWTYPE; e public."HostEvidenceEvent"%ROWTYPE;
BEGIN
  -- Match deletion/expiry lock order before touching the cleanup job. A
  -- concurrent retry must not deadlock by holding the job before the event.
  SELECT * INTO e FROM public."HostEvidenceEvent" WHERE event_id=p_event;
  IF NOT FOUND THEN RETURN FALSE; END IF;
  PERFORM 1 FROM public."HostEvidenceWorkspace" WHERE owner_id=e.owner_id AND trip_id=e.trip_id
    AND workspace_key=e.workspace_key FOR UPDATE;
  IF NOT FOUND THEN RETURN FALSE; END IF;
  SELECT * INTO c FROM public."HostEvidenceCleanup" WHERE event_id=p_event FOR UPDATE;
  IF NOT FOUND THEN RETURN FALSE; END IF;
  IF c.completed_at IS NOT NULL THEN RETURN TRUE; END IF;
  UPDATE public."HostEvidenceEvent" SET body=NULL,input_digest=NULL,session_ref=NULL WHERE event_id=p_event AND deleted_at IS NOT NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'deletion marker missing'; END IF;
  UPDATE public."HostEvidenceCleanup" SET completed_at=clock_timestamp() WHERE event_id=p_event;
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.host_evidence_cleanup_candidate(TEXT) FROM PUBLIC;
